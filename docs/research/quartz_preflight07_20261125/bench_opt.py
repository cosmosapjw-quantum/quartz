"""Exact same-input reference checks, timed pure Python kernels only."""
import importlib.util,json,time,statistics as S,random
from pathlib import Path
from engine import D,ROOT
import rules as new
p=ROOT/'docs/research/quartz_fouraxis06_20261125/rules.py'
sp=importlib.util.spec_from_file_location('old_rules',p);old=importlib.util.module_from_spec(sp);sp.loader.exec_module(old)
f=old.fixtures();h=f['draw'];inputs=[h[:t] for t in range(0,225,4)]+list(f.values())
count=0;cases=[]
for rule in new.ADMITTED:
    for seq in inputs:
        a=old.replay(seq,rule);b=new.replay(seq,rule);assert a==b
        assert new.features(seq)==old.features(seq)
        assert new.orbit_board(*a[:2],rule)==old.orbit_board(*a[:2],rule)
        assert new.orbit_history(seq)==old.orbit_history(seq)
        count+=4
        if a[2] is None:
            assert new.proof_reference(*a[:2],rule)==old.proof_reference(*a[:2],rule);count+=1
            cases.append((seq,rule))
    cur=new.ReplayCursor([],rule)
    for i,m in enumerate(h):cur.push(m);assert cur.snapshot()==old.replay(h[:i+1],rule);count+=1
# parity for random legal games generated by uniformly chosen moves, no NN games
rng=random.Random(107)
for _ in range(20):
    rule=new.ADMITTED[_%2];seq=[]
    for i in range(40):
        b,p,w=old.replay(seq,rule)
        if w is not None:break
        seq.append(rng.choice([a for a,v in enumerate(b) if not v]))
    a=old.replay(seq,rule);assert new.replay(seq,rule)==a and new.features(seq)==old.features(seq);count+=2
    if a[2] is None:assert new.proof_reference(*a[:2],rule)==old.proof_reference(*a[:2],rule);count+=1
# fixed representative cases, three interleaved repeats
cases=cases[::max(1,len(cases)//24)][:24]
def run(mod,kind):
    t=time.perf_counter_ns()
    for h,r in cases:
        b,p,w=mod.replay(h,r)
        if kind=='proof':mod.proof_reference(b,p,r)
        elif kind=='features':mod.features(h)
        elif kind=='D4':mod.orbit_board(b,p,r)
        else:
            for i in range(len(h)+1):mod.replay(h[:i],r)
    return (time.perf_counter_ns()-t)/1e6
res={}
for kind in ('proof','features','D4','repeated_replay'):
    oo=[];nn=[]
    for i in range(3):
        if i%2:nn.append(run(new,kind));oo.append(run(old,kind))
        else:oo.append(run(old,kind));nn.append(run(new,kind))
    res[kind]=dict(old_ms=oo,new_ms=nn,median_speedup=S.median(oo)/S.median(nn))
out=dict(assertions=count,representative_cases=len(cases),timings=res,scope='pure reference kernels, not native MCTS strength or end-to-end throughput')
(D/'C07_OPT_BENCH.json').write_text(json.dumps(out,sort_keys=True,indent=2)+'\n');print(json.dumps(out))
