import sys, os, pathlib, subprocess, hashlib, json, datetime
ROOT=pathlib.Path('/home/cosmosapjw/quantum/research/quartz_kinetic39_voc_20261126')
B=pathlib.Path('/home/cosmosapjw/Dropbox/personal_projects/quartz_kinetic39_voc_backups')
BASE='e3b953e606f918c4f2f8b4d2620b74df0d9cc9ec'
BR='research/quartz-kinetic39-voc-20261126'
D=ROOT/'docs/research/quartz_kinetic39_voc_20261126'
def git(*args):
    return subprocess.check_output(['git','-C',str(ROOT),*args],text=True).strip()
def run(*args):
    subprocess.run(args,cwd=ROOT,check=True)
def sha(p):
    return hashlib.file_digest(p.open('rb'),'sha256').hexdigest()
def publish(stage,body,paths=()):
    B.mkdir(exist_ok=True)
    p=D/'stages'/f'{stage}.md'; p.parent.mkdir(exist_ok=True)
    content=f'# {stage}\n\n'+body.strip()+'\n'
    if p.exists(): assert p.read_text()==content
    else: p.write_text(content)
    files=[str(p.relative_to(ROOT)),*paths]
    run('git','add','-f','--',*files)
    run('git','diff','--cached','--check')
    parent=git('rev-parse','HEAD')
    run('git','commit','-m',f'research(kinetic39 {stage}): conditional signed computation value')
    head=git('rev-parse','HEAD'); tree=git('rev-parse','HEAD^{tree}')
    for f in files: git('ls-files','--error-unmatch',f)
    assert not git('status','--porcelain')
    name=f'{stage}-{head[:12]}.bundle'; bundle=B/name
    assert not bundle.exists()
    run('git','bundle','create',str(bundle),f'{BASE}..refs/heads/{BR}')
    run('git','bundle','verify',str(bundle))
    assert git('bundle','list-heads',str(bundle)).split()[0]==head
    digest=sha(bundle)
    try:run('git','push','--no-thin','origin',f'HEAD:refs/heads/{BR}')
    except subprocess.CalledProcessError:
        # A lost ACK is possible. Verify actual remote before one retry.
        remote0=git('ls-remote','origin',f'refs/heads/{BR}').split()
        if not remote0 or remote0[0]!=head:
            run('git','push','--no-thin','origin',f'HEAD:refs/heads/{BR}')
    remote=git('ls-remote','origin',f'refs/heads/{BR}').split()[0]; assert remote==head
    receipt={'stage':stage,'head':head,'parent':parent,'tree':tree,'remote':remote,'bundle':name,'sha256':digest,'bytes':bundle.stat().st_size,'utc':datetime.datetime.now(datetime.timezone.utc).isoformat(),'files':files}
    latest=B/'LATEST.json'; old=json.loads(latest.read_text()) if latest.exists() else None
    with (B/'STAGE_RECEIPTS.jsonl').open('a') as f: f.write(json.dumps(receipt)+'\n')
    tmp=B/'LATEST.tmp'; tmp.write_text(json.dumps(receipt,indent=2)); tmp.replace(latest)
    # Only older archive generated by this exact run, with same verified ancestry.
    if old:
        prev=B/old['bundle']; assert prev.parent==B and prev.is_file()
        assert sha(prev)==old['sha256']
        assert git('merge-base',old['head'],head)==old['head']
        assert git('bundle','list-heads',str(bundle)).split()[0]==head
        prev.unlink()
        with (B/'CLEANUP.jsonl').open('a') as f: f.write(json.dumps({'removed':old['bundle'],'old_sha256':old['sha256'],'superseding':name,'old_head':old['head'],'new_head':head})+'\n')
    print('STAGE_RECEIPT',stage,head,tree,digest,flush=True)
if __name__=='__main__':
    publish(sys.argv[1],sys.argv[2],sys.argv[3:])
